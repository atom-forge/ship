/**
 * GitHub Actions publishing template for projects initialized with Ship.
 *
 * The wizard asks the user to confirm the package manager and verification
 * commands. This module turns those choices into a tag-triggered, OIDC-enabled
 * workflow. Values are emitted as YAML strings rather than interpolated shell
 * commands, and validation never rewrites a tag's package version.
 */
import {fail} from './errors.js';

export const managers = ['npm', 'bun', 'pnpm', 'yarn'];

export function publishWorkflow({manager, managerVersion, install, verify, tagPrefix = 'v', self = false}) {
  if (!managers.includes(manager)) fail(`Unsupported package manager: ${manager}`);
  if (!/^\d+\.\d+\.\d+$/.test(managerVersion)) fail('Use an exact package manager version such as 1.4.0.');
  const setup = manager === 'bun' ? [
    '      - uses: oven-sh/setup-bun@v2',
    '        with:',
    `          bun-version: ${JSON.stringify(managerVersion)}`,
  ] : manager !== 'npm' ? [
    `      - run: ${JSON.stringify(`npm install --global ${manager}@${managerVersion}`)}`,
  ] : [];
  const steps = verify.map(command => `      - run: ${JSON.stringify(command)}`);
  return [
    '# Generated by ship-it init. Verification commands are project-specific.',
    'name: Publish to npm', '',
    'on:', '  push:', '    tags:', `      - ${JSON.stringify(`${tagPrefix}*`)}`, '',
    'permissions:', '  contents: read', '',
    'concurrency:', '  group: npm-publish-${{ github.ref }}', '  cancel-in-progress: false', '',
    'jobs:', '  publish:', '    runs-on: ubuntu-latest',
    '    permissions:', '      contents: read', '      id-token: write',
    '    steps:', '      - uses: actions/checkout@v4', '        with:', '          persist-credentials: false',
    '      - uses: actions/setup-node@v6', '        with:', "          node-version: '24'",
    "          registry-url: 'https://registry.npmjs.org'", '          package-manager-cache: false',
    `      - run: npm install --global npm@${manager === 'npm' ? managerVersion : '11.16.0'}`,
    ...setup,
    ...(install ? [`      - run: ${JSON.stringify(install)}`] : []),
    `      - run: ${JSON.stringify(self ? 'node bin/ship-it.js validate' : `${manager} run pub-validate`)}`,
    ...steps,
    '      - run: npm pack --dry-run --ignore-scripts',
    // npm generates provenance automatically when the repository supports it.
    '      - run: npm publish --access public --ignore-scripts', '',
  ].join('\n');
}
